set -euo pipefail
cd "$(dirname "$0")/../.."
[ "${CRM_TEST_ENV:-}" = "1" ] || { echo 'REFUSING: CRM_TEST_ENV=1 required' >&2; exit 2; }
. scripts/docker-loopback.sh
loopback_stack_lock crm-test
loopback_verify_container supabase_db_crm-test supabase_db_crm-test crm-test crm-test-loopback 5432/tcp 54342
marker=$(docker exec supabase_db_crm-test psql -U postgres -d postgres -X -At -c 'SELECT project_id FROM crm_test_guard.identity WHERE singleton AND marker_version=1')
[ "$marker" = crm-test ] || { echo 'REFUSING: crm-test identity missing' >&2; exit 2; }
python3 - <<'PY'
import concurrent.futures, json, subprocess, time, uuid

company = 'a0000000-0000-4000-8000-0000000000c1'
owner = 'a0000000-0000-4000-8000-000000000001'
invoice, q1, q2, q3, q4 = [str(uuid.uuid4()) for _ in range(5)]
email = f'quittung-concurrency-{invoice}@example.test'
auth = f'''SET LOCAL ROLE authenticated;
SELECT set_config('request.jwt.claims','{{"sub":"{owner}","role":"authenticated"}}',true);'''
items = '''[{"id":"one","beschreibung":"Concurrency service","satz":"","betrag":100,"checked":true,"is_custom":false}]'''

def db(sql, app='quittung_concurrency_check'):
    process = subprocess.run(
        ['docker','exec','-i','supabase_db_crm-test','psql','-U','postgres','-d','postgres','-X','-At','-v','ON_ERROR_STOP=1'],
        input=f"SET application_name='{app}'; SET lock_timeout='10s'; SET statement_timeout='20s';\n" + sql,
        text=True,capture_output=True)
    if process.returncode:
        raise RuntimeError(process.stderr)
    return process.stdout.strip().splitlines()[-1]

def overlap(first, second, app):
    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as executor:
        holding = executor.submit(db, first, app)
        deadline = time.monotonic() + 8
        while db(f"SELECT EXISTS(SELECT 1 FROM pg_stat_activity WHERE application_name='{app}' AND wait_event='PgSleep')") != 't':
            if holding.done():
                holding.result()
                raise RuntimeError('Holding transaction finished before concurrency checkpoint')
            if time.monotonic() > deadline:
                raise RuntimeError('Holding transaction did not reach concurrency checkpoint')
            time.sleep(0.05)
        waiting = executor.submit(db, second, app + '_second')
        holding.result()
        waiting.result()

def receipt_sql(qid, linked=True):
    link_columns = ',rechnung_id' if linked else ''
    link_values = f",'{invoice}'" if linked else ''
    return f'''INSERT INTO public.quittungen(id,company_id,customer_id,customer_name,positionen,mwst_satz{link_columns})
      SELECT '{qid}','{company}',customer_id,customer_name,'{items}',0{link_values}
      FROM public.rechnungen WHERE id='{invoice}';'''

def invoice_amount(amount):
    return f'''UPDATE public.rechnungen SET
      positionen='[{{"beschreibung":"Concurrency service","menge":1,"einzelpreis":{amount},"betrag":{amount},"einheit":"pauschal"}}]',
      zwischensumme={amount},total={amount},gesamttotal={amount} WHERE id='{invoice}';'''

results = []
try:
    db(f'''BEGIN; {auth}
    INSERT INTO public.rechnungen(id,company_id,customer_name,customer_email,positionen,zwischensumme,mwst_satz,mwst_betrag,total,rabatt,gesamttotal,status,datum,faellig_am)
    VALUES('{invoice}','{company}','Concurrency fixture','{email}','[{{"beschreibung":"Concurrency service","menge":1,"einzelpreis":100,"betrag":100,"einheit":"pauschal"}}]',100,0,0,100,0,100,'entwurf',CURRENT_DATE,CURRENT_DATE+30);
    COMMIT;''')
    overlap(f'BEGIN; {auth} {receipt_sql(q1)} SELECT pg_sleep(1.5); COMMIT;',
            f'BEGIN; {auth} {invoice_amount(200)} COMMIT;', 'quittung_link_first')
    assert db(f"SELECT payment_open_amount=200 FROM public.quittungen WHERE id='{q1}'") == 't'
    results.append('C1: uncommitted receipt link followed by invoice edit retains current balance')

    overlap(f'BEGIN; {auth} {invoice_amount(300)} SELECT pg_sleep(1.5); COMMIT;',
            f'BEGIN; {auth} {receipt_sql(q2)} COMMIT;', 'quittung_invoice_first')
    assert db(f"SELECT count(*)=2 AND bool_and(payment_open_amount=300) FROM public.quittungen WHERE id IN ('{q1}','{q2}')") == 't'
    results.append('C2: invoice edit followed by new receipt link reads committed balance')

    overlap(f'BEGIN; {auth} {receipt_sql(q3,False)} SELECT pg_sleep(1.5); COMMIT;',
            f'BEGIN; {auth} {receipt_sql(q4,False)} COMMIT;', 'quittung_counter_first')
    assert db(f"SELECT count(*)=2 AND count(DISTINCT quittung_nr)=2 FROM public.quittungen WHERE id IN ('{q3}','{q4}')") == 't'
    results.append('C3: concurrent same-company receipt inserts both commit with distinct numbers')
finally:
    # Only IDs/emails generated by this run; no payment or issued document exists.
    db(f'''BEGIN;
      DELETE FROM public.quittungen WHERE id IN ('{q1}','{q2}','{q3}','{q4}');
      DELETE FROM public.rechnungen WHERE id='{invoice}';
      DELETE FROM public.customers WHERE company_id='{company}' AND primary_email='{email}';
      COMMIT;''')
print(json.dumps({'target':'crm-test / 127.0.0.1:54342','passed':len(results),'cases':results,'synthetic_rows_cleaned':True},indent=2))
PY
